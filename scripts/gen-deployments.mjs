#!/usr/bin/env node
// Writes packages/chain/src/deployments.generated.ts from contracts/deployments/<chainId>.json.
// The committed deployment records are embedded in the source so a bundled binary never has to
// find contracts/deployments/ on the machine it runs on. The local-Anvil record (31337.json) is
// per-machine and gitignored, so it is never embedded — loadDeployment still reads it from disk.
// Run with no argument to update the committed file, or with an output path to render elsewhere
// (the freshness test renders to a temp file and diffs it against the committed one).
import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = fileURLToPath(new URL("../", import.meta.url))
const DEPLOYMENTS_DIR = join(ROOT, "contracts", "deployments")
const DEFAULT_OUT = join(ROOT, "packages", "chain", "src", "deployments.generated.ts")

function render(dir) {
  const entries = []
  for (const file of readdirSync(dir).filter((name) => name.endsWith(".json")).sort()) {
    const chainId = file.slice(0, -".json".length)
    if (chainId === "31337") continue
    entries.push(`  ${JSON.stringify(chainId)}: ${readFileSync(join(dir, file), "utf8").trim()},`)
  }
  return `// GENERATED by scripts/gen-deployments.mjs — do not edit by hand.
// The committed contract deployment records, embedded so a bundled binary never has to find
// contracts/deployments/ on the machine it runs on. The local-Anvil record (31337.json) is
// per-machine and gitignored, so it is not here — loadDeployment reads that one from disk.

export const EMBEDDED_DEPLOYMENTS: Record<string, unknown> = {
${entries.join("\n")}
}
`
}

const out = process.argv[2] ?? DEFAULT_OUT
writeFileSync(out, render(DEPLOYMENTS_DIR))
console.log(`wrote ${out}`)
